"""Generate CONTINUATION.md from installed live state, not hardcoded pass labels.

State is inventory, not approval. Never deletes or alters pose revisions.
"""
from __future__ import annotations
import argparse, datetime, json, os
from pathlib import Path
try:
    from pose_common import ROOT,read_json
except ImportError:
    ROOT=Path(__file__).resolve().parents[1]
    def read_json(p):return json.loads(Path(p).read_text(encoding='utf-8'))


def latest_snapshot(root):
    folders=[x for x in (root/'snapshots').glob('batch-*-pass-*') if x.is_dir() and (x/'batch-summary.json').is_file()]
    return max(folders,key=lambda p:(p.name.rsplit('_',1)[-1],p.stat().st_mtime)) if folders else None


def generate(root=ROOT, snapshot=None, output=None):
    root=Path(root)
    p=read_json(root/'project.json')
    src=read_json(root/'source/dataset.json')
    snap=Path(snapshot) if snapshot else latest_snapshot(root)
    if snap is not None and not snap.is_absolute():
        snap=root/snap
    data=read_json(snap/'batch-summary.json') if snap else {}
    results=data.get('results',[])
    stamp=datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d %H:%M UTC')
    lines=[
        '# SPOSE — generated continuation checkpoint','',
        f'Generated: **{stamp}**. Generated by `scripts/update_continuation.py`; regenerate after each batch.','',
        '## Source of authority','',
        '- Live local `project.json`, `source/dataset.json`, `tracking/progress.sqlite`, and actual `poses/` revisions are authoritative.',
        '- This document is a derived human-readable snapshot; if older than the tracker, regenerate it.',
        '- This standalone remote library has no outer `remote/` wrapper. The shared Blender template stays local.',
        f"- Project ID: `{p.get('project_id','unknown')}`.",
        f"- Source ID: `{src.get('source_id','?')}`; revision `{src.get('source_revision','?')}`; checkpoint `{src.get('checkpoint','?')}`.",
        f"- Source catalog SHA-256: `{src.get('catalog_sha256','?')}`.",
        '- Fixed source inventory: 28 families, 276 V00 bases, 3,036 total records, subject to the live source registration.','',
        '## Latest recorded batch','',
    ]
    if snap:
        lines += [f"- Batch: `{data.get('batch_label','unknown')}`; pass: `{data.get('pass_label','unknown')}`; snapshot: `{snap.relative_to(root).as_posix()}`.",
                  f"- Attempted items: {len(results)}; built revision references: {sum(1 for r in results if r.get('revision') is not None)}.",
                  '- `reused_existing_package` means no new revision, regardless of the pass label.',
                  '', '| Pose | Revision | Build status | Stability | Issues |',
                  '|---|---|---|---|---:|']
        for r in results:
            rv=r.get('revision')
            rv=f'r{int(rv):03d}' if isinstance(rv,int) else '—'
            lines.append(f"| `{r.get('pose_id','?')}` | {rv} | {r.get('build_status','unknown')} | {r.get('stability','unreviewed')} | {r.get('issue_count',0)} |")
    else:
        lines.append('- No batch snapshot found; inspect `tracking/` and `ROADMAP.json` for live history.')
    road_path=root/'ROADMAP.json'
    if road_path.is_file():
        roadmap=read_json(road_path)
        s=roadmap.get('summary',{})
        lines += ['', '## Recorded V00 progress','',
                  f"- Built: {s.get('v00_built','?')}/{s.get('base_total','?')}; attempted: {s.get('v00_attempted','?')}; accepted (optional): {s.get('v00_accepted','?')}."]
    lines += ['', '## Workflow and next action','',
              '- Treat each batch as five poses and normally two passes; a third pass is optional based on human visual judgment.',
              '- All five are attempted in a single run even if some produce geometry warnings or fail.',
              '- Quality, source REVIEW/EXCLUDE flags and acceptance are metadata, not permission gates.',
              '- For new pose adjustments, create new packages with new identity/timestamps. Rerunning identical packages may reuse old revisions.',
              '- `snapshots/` contains persistent history; `review/` and `upload/` are flat, disposable derived artifacts.',
              '- To recreate the latest exchange without Blender: `python scripts/refresh_exchange.py`.',
              '- To run an installed batch: `python scripts/run_pose_batch.py --plan batches/BATCH-001.json --blender "<BLENDER_EXE>"` (change plan as appropriate).',
              '- Return only `upload/spose-remote-feedback-batch-XXXX-pass-YY_<timestamp>.zip`; it contains all poses and portable context.',
              '- The next batch and any requested additional calibration should be decided by the user, not automatically inferred from the file name.',
              '', '## Cold-start reading order','',
              '1. `README.md` and `AGENTS.md` (scope, authority, safety).',
              '2. `SKILL.md` and `WORKFLOW.md` (operational procedures).',
              '3. `GUIDE.md` and `docs/ARCHITECTURE.md` (commands and ownership).',
              '4. `docs/SCHEMAS.md`, `docs/MAINTENANCE.md` and source/rig specifications.',
              '5. Current `batch-summary.json`, pose inputs and images for geometric calibration.',
              '', '## Explicitly out of scope','',
              '- This infrastructure checkpoint does not validate 3D correctness or approve poses.',
              '- The local Blender asset, SQLite, and any `.blend` revisions are not included in portable context.',
              '']
    dest=Path(output) if output else root/'CONTINUATION.md'
    dest.parent.mkdir(parents=True,exist_ok=True)
    dest.write_text('\n'.join(lines),encoding='utf-8')
    return dest


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root',type=Path,default=ROOT)
    parser.add_argument('--snapshot',type=Path)
    parser.add_argument('--output',type=Path)
    args=parser.parse_args()
    print(generate(args.root,args.snapshot,args.output))

if __name__=='__main__':main()
